"""The script commands' names, from the pinned decompilation's command tables (each group's
{handler, continuation} pairs), into studio/core/missions/command_names.cpp (committed); a table the
decompilation lacks is left out.
    python studio/tools/command_names.py"""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DECOMP = ROOT / "external" / "khdays-decomp"
OUT = ROOT / "studio" / "core" / "missions" / "command_names.cpp"

# group -> (the table's symbol, where it comes from)
GROUPS = [
    (0, "data_02042640", "the main program's (static)"),
    (2, "data_ov002_0207f134", "Ov002_ConstructGameplayScene"),
    (3, "data_ov012_0205caf4", "Ov012_InitOpeningScene (the scenes played in a mission)"),
    (4, "data_ov002_0207f484", "Ov002_CreateSceneRegistry"),
    # the panels: Ov002_SwitchPanelOverlay installs row n's table as group n + 5
    (5, "data_ov013_0207fec8", "panel 0 (ov013)"),
    (6, "data_ov014_020808e0", "panel 1 (ov014)"),
    (7, "data_ov019_0207fd60", "panel 2 (ov019)"),
    (8, "data_ov016_020826e0", "panel 3 (ov016, field breakables)"),
    (9, "data_ov020_020800c0", "panel 4 (ov020)"),
    (10, "data_ov015_02082904", "panel 5 (ov015, field pickups)"),
    (13, "data_ov017_02080e40", "panel 8 (ov017, field deposits)"),
    (16, "data_ov018_0207fa60", "panel 11 (ov018)"),
    (17, "data_ov021_02080f20", "panel 12 (ov021, prize boxes)"),
    (0x13, "data_ov069_020baa84", "Ov002_BringUpMissionOverlays (ov069)"),
]


def table(symbol):
    """The table's entries (names, None for 0), or None when not found."""
    for path in (DECOMP / "src").rglob("*.c"):
        text = path.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"\b" + re.escape(symbol) + r"\s*\[\s*\d*\s*\]\s*=\s*\{(.*?)\};", text, re.S)
        if m:
            body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
            items = [t.strip() for t in body.split(",")]
            items = [t for t in items if t]
            out = []
            for t in items:
                t = re.sub(r"^\(\s*void\s*\*\s*\)", "", t.strip())  # a cast: (void *)Name
                t = t.lstrip("&").strip()
                out.append(None if t in ("0", "NULL") else t)
            return out, path.relative_to(DECOMP).as_posix()
    return None, None


def main():
    commit = subprocess.run(
        ["git", "-C", str(DECOMP), "log", "-1", "--format=%h"], capture_output=True, text=True
    ).stdout.strip()
    rows = []
    sources = []
    for group, symbol, origin in GROUPS:
        entries, path = table(symbol)
        if entries is None:
            sources.append(f"//   group {group:2}: {symbol} -- not in the decompilation ({origin})")
            continue
        sources.append(f"//   group {group:2}: {symbol}, {path} ({origin})")
        for c in range(0, len(entries), 2):
            handler = entries[c]
            cont = entries[c + 1] if c + 1 < len(entries) else None
            if handler is None and cont is None:
                continue
            rows.append((group, c // 2, handler or "", cont or ""))
    lines = [
        "// Generated by studio/tools/command_names.py from the pinned decompilation",
        f"// (khdays-decomp {commit}); do not edit. Each group's table:",
        *sources,
        '#include "core/missions/command_names.h"',
        "",
        "namespace studio {",
        "",
        "namespace {",
        "",
        "const CommandName kNames[] = {",
    ]
    for g, c, h, k in rows:
        lines.append(f'    {{{g}, {c}, "{h}", "{k}"}},')
    lines += [
        "};",
        "",
        "}  // namespace",
        "",
        "const CommandName* command_name(int group, int command) {",
        "    for (const auto& n : kNames) {",
        "        if (n.group == group && n.command == command) return &n;",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "std::size_t command_name_count() {",
        "    return sizeof(kNames) / sizeof(kNames[0]);",
        "}",
        "",
        "}  // namespace studio",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(OUT, len(rows), "commands")


if __name__ == "__main__":
    main()
