"""Compile the renderer's shaders for every graphics backend SDL3 supports.

    python port/tools/build_shaders.py [name ...]

Each port/shaders/<name>.hlsl holds the entry points of its stages --
vs_main (vertex), ps_main (pixel), cs_main (compute), whichever it has. For
each stage the Vulkan SDK's tools make:

    DXIL    (Direct3D 12)  dxc -T <stage>_6_0
    SPIR-V  (Vulkan)       dxc -spirv
    MSL     (Metal)        spirv-cross --msl, from the SPIR-V

and the results are written as C arrays to
port/host/render/generated/<name>_<stage>.h, which the port includes. The build
never runs this script: the generated headers are committed, so building
the port needs no shader tools. Run it after changing a shader, with the
Vulkan SDK installed (VULKAN_SDK set, as its installer does).

Resource layout (what SDL3's GPU API expects, SDL_gpu.h):
- vertex shaders: textures and samplers in space0, uniforms in space1;
- pixel shaders: textures and samplers in space2, uniforms in space3; for
  SPIR-V a texture and its sampler must be one combined image sampler:
  declare both with [[vk::combinedImageSampler]] and the same
  [[vk::binding(n, set)]];
- compute shaders: read-only textures, then read-only buffers, in t
  registers of space0; read-write textures, then read-write buffers, in u
  registers of space1; uniforms in b registers of space2. A storage image
  needs its format for SPIR-V: [[vk::image_format("r32ui")]].
"""
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHADERS = ROOT / "port" / "shaders"
OUT = ROOT / "port" / "host" / "render" / "generated"

STAGES = {"vs_main": "vs", "ps_main": "ps", "cs_main": "cs"}


def tool(name: str) -> str:
    sdk = os.environ.get("VULKAN_SDK")
    candidates = []
    if sdk:
        candidates.append(Path(sdk) / "Bin" / (name + ".exe"))
        candidates.append(Path(sdk) / "bin" / name)
    found = next((str(c) for c in candidates if c.exists()), None) or shutil.which(name)
    if not found:
        sys.exit(f"build_shaders: {name} not found (install the Vulkan SDK and set VULKAN_SDK)")
    return found


def run(args: list[str]) -> None:
    result = subprocess.run(args, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if result.returncode != 0:
        sys.exit(f"build_shaders: {' '.join(args)}\n{result.stdout}{result.stderr}")


def version(exe: str) -> str:
    result = subprocess.run([exe, "--version"], capture_output=True, text=True, encoding="utf-8",
                            errors="replace")
    line = (result.stdout or result.stderr).strip().splitlines()
    return line[0] if line else "unknown"


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows)
    return (f"static const unsigned char {name}[] = {{\n    {body}\n}};\n"
            f"static const unsigned int {name}_size = {len(data)}u;\n")


def build(source: Path, dxc: str, cross: str, versions: str, work: Path) -> None:
    text = source.read_text(encoding="utf-8")
    stages = [(entry, stage) for entry, stage in STAGES.items() if re.search(rf"\b{entry}\s*\(", text)]
    if not stages:
        sys.exit(f"build_shaders: {source.name} has none of {', '.join(STAGES)}")
    for entry, stage in stages:
        profile = f"{stage}_6_0"
        base = f"{source.stem}_{stage}"
        dxil = work / f"{base}.dxil"
        spirv = work / f"{base}.spv"
        msl = work / f"{base}.metal"
        run([dxc, "-nologo", "-T", profile, "-E", entry, "-O3", "-Fo", str(dxil), str(source)])
        run([dxc, "-nologo", "-spirv", "-fspv-target-env=vulkan1.1", "-T", profile, "-E", entry, "-O3",
             "-Fo", str(spirv), str(source)])
        run([cross, str(spirv), "--msl", "--msl-version", "20100", "--output", str(msl)])
        header = OUT / f"{base}.h"
        header.write_text(
            f"/* Generated by port/tools/build_shaders.py from port/shaders/{source.name}\n"
            f" * ({entry}); do not edit. Tools: {versions}. */\n"
            + c_array(f"{base}_dxil", dxil.read_bytes())
            + c_array(f"{base}_spirv", spirv.read_bytes())
            + c_array(f"{base}_msl", msl.read_bytes() + b"\0")
            + f"#define {base.upper()}_ENTRY \"{entry}\"\n",
            encoding="utf-8", newline="\n")
        print(f"{header.relative_to(ROOT)}: DXIL {dxil.stat().st_size} B, SPIR-V {spirv.stat().st_size} B, "
              f"MSL {msl.stat().st_size} B")


def main() -> int:
    dxc, cross = tool("dxc"), tool("spirv-cross")
    versions = f"{version(dxc)}; spirv-cross"
    names = sys.argv[1:]
    sources = [SHADERS / f"{n}.hlsl" for n in names] if names else sorted(SHADERS.glob("*.hlsl"))
    if not sources:
        sys.exit("build_shaders: no shaders in port/shaders")
    OUT.mkdir(parents=True, exist_ok=True)
    work = ROOT / "build" / "port" / "shaders"
    work.mkdir(parents=True, exist_ok=True)
    for source in sources:
        if not source.exists():
            sys.exit(f"build_shaders: {source} does not exist")
        build(source, dxc, cross, versions, work)
    return 0


if __name__ == "__main__":
    sys.exit(main())
